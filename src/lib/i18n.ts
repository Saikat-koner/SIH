export const getTranslation = (arg1: string, arg2?: string): string => {
  if (!arg1) return '';

  let langCode = 'en';
  let rawKey = arg1;

  // Flexible argument handling: whether called as (lang, key) or (key, lang)
  if (arg2) {
    if (DICTIONARY[arg1] || SUPPORTED_LANGUAGES.some((l) => l.code === arg1) || (arg1.length <= 3 && !rawKey.includes(' '))) {
      langCode = arg1;
      rawKey = arg2;
    } else {
      langCode = arg2;
      rawKey = arg1;
    }
  }

  const canonicalKey = (KEY_ALIASES[rawKey] || rawKey) as keyof Translations;
  const targetDict = DICTIONARY[langCode] || DICTIONARY['en'];

  if (targetDict) {
    if ((targetDict as any)[rawKey]) {
      return (targetDict as any)[rawKey]!;
    }
    if (targetDict[canonicalKey]) {
      return targetDict[canonicalKey]!;
    }
  }

  const enDict = DICTIONARY['en'];
  if (enDict) {
    if ((enDict as any)[rawKey]) {
      return (enDict as any)[rawKey]!;
    }
    if (enDict[canonicalKey]) {
      return enDict[canonicalKey]!;
    }
  }

  if (DEFAULT_FALLBACKS[rawKey]) {
    return DEFAULT_FALLBACKS[rawKey];
  }
  if (DEFAULT_FALLBACKS[canonicalKey]) {
    return DEFAULT_FALLBACKS[canonicalKey];
  }

  return rawKey;
};
